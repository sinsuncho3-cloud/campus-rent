-- Reusable approval transaction primitive, not a replacement for server authentication.
-- P_ADMIN_ID MUST be supplied from an authenticated backend session.
CREATE OR REPLACE PROCEDURE APPROVE_REQUEST_ITEM (
  P_ITEM_ID IN NUMBER,
  P_ADMIN_ID IN NUMBER,
  P_EXPECTED_VERSION IN NUMBER
) AUTHID DEFINER IS
  V_ITEM REQUEST_ITEM%ROWTYPE;
  V_KIND REQUEST_ITEM.ITEM_KIND%TYPE;
  V_EQ_ID REQUEST_ITEM.EQUIPMENT_ID%TYPE;
  V_FAC_ID REQUEST_ITEM.FACILITY_ID%TYPE;
  V_ALLOWED CHAR(1);
  V_STATUS VARCHAR2(10);
  V_CAPACITY NUMBER;
  V_COUNT NUMBER;
  V_OPEN CHAR(5);
  V_CLOSE CHAR(5);
  V_DAY NUMBER;
BEGIN
  SAVEPOINT APPROVAL_START;
  IF P_ITEM_ID IS NULL OR P_ADMIN_ID IS NULL OR P_EXPECTED_VERSION IS NULL THEN
    RAISE_APPLICATION_ERROR(-20001,'Required approval parameters are missing.');
  END IF;
  SELECT COUNT(*) INTO V_COUNT FROM APP_USER WHERE USER_ID=P_ADMIN_ID AND ROLE_CODE='ADMIN';
  IF V_COUNT<>1 THEN RAISE_APPLICATION_ERROR(-20002,'Administrator required.'); END IF;

  -- First identify the resource; then all writers must lock resource -> item.
  SELECT ITEM_KIND,EQUIPMENT_ID,FACILITY_ID INTO V_KIND,V_EQ_ID,V_FAC_ID
    FROM REQUEST_ITEM WHERE REQUEST_ITEM_ID=P_ITEM_ID;
  IF V_KIND='E' THEN
    SELECT LEND_ALLOWED_YN,OPERATING_STATUS INTO V_ALLOWED,V_STATUS
      FROM EQUIPMENT WHERE EQUIPMENT_ID=V_EQ_ID FOR UPDATE WAIT 5;
  ELSE
    SELECT USE_ALLOWED_YN,OPERATING_STATUS,CAPACITY INTO V_ALLOWED,V_STATUS,V_CAPACITY
      FROM FACILITY WHERE FACILITY_ID=V_FAC_ID FOR UPDATE WAIT 5;
  END IF;
  SELECT * INTO V_ITEM FROM REQUEST_ITEM WHERE REQUEST_ITEM_ID=P_ITEM_ID FOR UPDATE WAIT 5;
  IF V_ITEM.ITEM_KIND<>V_KIND OR NVL(V_ITEM.EQUIPMENT_ID,-1)<>NVL(V_EQ_ID,-1)
     OR NVL(V_ITEM.FACILITY_ID,-1)<>NVL(V_FAC_ID,-1) THEN
    RAISE_APPLICATION_ERROR(-20003,'Resource changed; reload and retry.');
  END IF;
  IF V_ITEM.STATUS_CODE<>'PENDING' OR V_ITEM.ROW_VERSION<>P_EXPECTED_VERSION THEN
    RAISE_APPLICATION_ERROR(-20004,'Stale request status or row version.');
  END IF;
  IF V_ALLOWED<>'Y' OR V_STATUS<>'NORMAL' THEN
    RAISE_APPLICATION_ERROR(-20005,'Resource is not available for use.');
  END IF;
  IF V_ITEM.USE_START_AT<=LOCALTIMESTAMP OR V_ITEM.USE_END_AT<=V_ITEM.USE_START_AT THEN
    RAISE_APPLICATION_ERROR(-20006,'Invalid or past use period.');
  END IF;
  IF V_ITEM.PURPOSE_ID IS NOT NULL THEN
    SELECT COUNT(*) INTO V_COUNT FROM USE_PURPOSE WHERE PURPOSE_ID=V_ITEM.PURPOSE_ID AND ENABLED_YN='Y';
    IF V_COUNT<>1 THEN RAISE_APPLICATION_ERROR(-20007,'Purpose is disabled.'); END IF;
  END IF;
  IF V_KIND='E' THEN
    SELECT COUNT(*) INTO V_COUNT FROM EQUIPMENT E
      JOIN EQUIPMENT_MODEL M ON M.MODEL_ID=E.MODEL_ID
      JOIN EQUIPMENT_TYPE T ON T.TYPE_ID=M.TYPE_ID
      WHERE E.EQUIPMENT_ID=V_EQ_ID AND T.ENABLED_YN='Y';
    IF V_COUNT<>1 THEN RAISE_APPLICATION_ERROR(-20008,'Equipment type is disabled.'); END IF;
  ELSE
    IF V_ITEM.PEOPLE_COUNT IS NULL OR V_ITEM.PEOPLE_COUNT<1 OR V_ITEM.PEOPLE_COUNT>V_CAPACITY THEN
      RAISE_APPLICATION_ERROR(-20009,'Facility capacity exceeded.');
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM FACILITY_PURPOSE WHERE FACILITY_ID=V_FAC_ID AND PURPOSE_ID=V_ITEM.PURPOSE_ID;
    IF V_COUNT<>1 THEN RAISE_APPLICATION_ERROR(-20010,'Facility purpose not permitted.'); END IF;
    IF TRUNC(CAST(V_ITEM.USE_START_AT AS DATE))<>TRUNC(CAST(V_ITEM.USE_END_AT AS DATE)) THEN
      RAISE_APPLICATION_ERROR(-20011,'Facility reservation must be within one day.');
    END IF;
    V_DAY:=TRUNC(CAST(V_ITEM.USE_START_AT AS DATE))-TRUNC(CAST(V_ITEM.USE_START_AT AS DATE),'IW')+1;
    BEGIN
      SELECT OPEN_TIME,CLOSE_TIME INTO V_OPEN,V_CLOSE FROM FACILITY_HOURS
        WHERE FACILITY_ID=V_FAC_ID AND WEEKDAY_NO=V_DAY;
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20012,'Facility is closed that day.'); END;
    IF TO_CHAR(V_ITEM.USE_START_AT,'HH24:MI:SS.FF6')<V_OPEN||':00.000000'
       OR TO_CHAR(V_ITEM.USE_END_AT,'HH24:MI:SS.FF6')>V_CLOSE||':00.000000' THEN
      RAISE_APPLICATION_ERROR(-20013,'Outside facility operating hours.');
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM FACILITY_BLOCK
      WHERE FACILITY_ID=V_FAC_ID AND BLOCK_START_AT<V_ITEM.USE_END_AT AND BLOCK_END_AT>V_ITEM.USE_START_AT;
    IF V_COUNT>0 THEN RAISE_APPLICATION_ERROR(-20014,'Facility is blocked during that period.'); END IF;
  END IF;

  -- The parent resource lock serializes even when there are NO existing reservation rows to lock.
  SELECT COUNT(*) INTO V_COUNT FROM REQUEST_ITEM R
    WHERE R.REQUEST_ITEM_ID<>P_ITEM_ID
      AND ((V_KIND='E' AND R.EQUIPMENT_ID=V_EQ_ID) OR (V_KIND='F' AND R.FACILITY_ID=V_FAC_ID))
      AND R.STATUS_CODE IN ('APPROVED','CHECKED_OUT','RETURN_REQUESTED','RETURN_HOLD','IN_USE')
      AND R.USE_START_AT<V_ITEM.USE_END_AT AND R.USE_END_AT>V_ITEM.USE_START_AT;
  IF V_COUNT>0 THEN RAISE_APPLICATION_ERROR(-20015,'Conflicting approved reservation.'); END IF;
  UPDATE REQUEST_ITEM SET STATUS_CODE='APPROVED',ROW_VERSION=ROW_VERSION+1,UPDATED_AT=LOCALTIMESTAMP
    WHERE REQUEST_ITEM_ID=P_ITEM_ID;
  INSERT INTO REQUEST_STATUS_LOG (STATUS_LOG_ID,REQUEST_ITEM_ID,FROM_STATUS,TO_STATUS,CHANGED_BY,CHANGED_AT)
    VALUES (SQ_REQUEST_STATUS_LOG.NEXTVAL,P_ITEM_ID,'PENDING','APPROVED',P_ADMIN_ID,LOCALTIMESTAMP);
  -- Caller owns COMMIT. On exception only this procedure's work is undone.
EXCEPTION WHEN OTHERS THEN
  ROLLBACK TO APPROVAL_START;
  RAISE;
END;
