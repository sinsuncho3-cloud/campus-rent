-- Existing table/sequence names remain unchanged. New objects follow TBL_/SEQ_ convention.
ALTER TABLE FACILITY_BLOCK ADD (
  ENABLED_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CANCELLED_AT TIMESTAMP,
  CANCELLED_BY NUMBER(10),
  CANCEL_REASON VARCHAR2(500 CHAR),
  CONSTRAINT CK_FB_ENABLED CHECK (ENABLED_YN IN ('Y','N')),
  CONSTRAINT FK_FB_CANCEL_USER FOREIGN KEY (CANCELLED_BY) REFERENCES APP_USER(USER_ID),
  CONSTRAINT CK_FB_CANCEL CHECK (
    (ENABLED_YN='Y' AND CANCELLED_AT IS NULL AND CANCELLED_BY IS NULL AND CANCEL_REASON IS NULL) OR
    (ENABLED_YN='N' AND CANCELLED_AT IS NOT NULL AND CANCELLED_BY IS NOT NULL AND CANCEL_REASON IS NOT NULL))
);
CREATE TABLE TBL_FACILITY_BLOCK_LOG (
  AUDIT_ID NUMBER(10) NOT NULL,
  BLOCK_ID NUMBER(10) NOT NULL,
  FACILITY_ID NUMBER(10) NOT NULL,
  ACTION_CODE VARCHAR2(10 CHAR) NOT NULL,
  BEFORE_JSON CLOB,
  AFTER_JSON CLOB NOT NULL,
  REASON_TEXT VARCHAR2(500 CHAR) NOT NULL,
  ACTOR_ID NUMBER(10) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  CONSTRAINT PK_FB_LOG PRIMARY KEY(AUDIT_ID),
  CONSTRAINT FK_FBL_BLOCK FOREIGN KEY(BLOCK_ID) REFERENCES FACILITY_BLOCK(BLOCK_ID),
  CONSTRAINT FK_FBL_FAC FOREIGN KEY(FACILITY_ID) REFERENCES FACILITY(FACILITY_ID),
  CONSTRAINT FK_FBL_ACTOR FOREIGN KEY(ACTOR_ID) REFERENCES APP_USER(USER_ID),
  CONSTRAINT CK_FBL_ACTION CHECK(ACTION_CODE IN ('IMPORT','CREATE','UPDATE','CANCEL'))
);
CREATE SEQUENCE SEQ_FACILITY_BLOCK_LOG START WITH 1000 INCREMENT BY 1 MAXVALUE 9999999999 NOCYCLE CACHE 20;
CREATE INDEX IX_FBL_BLOCK ON TBL_FACILITY_BLOCK_LOG(BLOCK_ID,CREATED_AT);
CREATE INDEX IX_FBL_FAC ON TBL_FACILITY_BLOCK_LOG(FACILITY_ID);
CREATE INDEX IX_FBL_ACTOR ON TBL_FACILITY_BLOCK_LOG(ACTOR_ID);
CREATE INDEX IX_FB_CANCEL_USER ON FACILITY_BLOCK(CANCELLED_BY);
