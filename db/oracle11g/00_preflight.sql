DECLARE
  V_COUNT NUMBER;
BEGIN
  IF USER IN ('SYS','SYSTEM') THEN
    RAISE_APPLICATION_ERROR(-20100,'Use a dedicated application schema, never SYS/SYSTEM.');
  END IF;
  SELECT COUNT(*) INTO V_COUNT FROM USER_OBJECTS;
  IF V_COUNT>0 THEN
    RAISE_APPLICATION_ERROR(-20101,'Installation requires an EMPTY schema. Do not rerun after partial DDL.');
  END IF;
  SELECT COUNT(*) INTO V_COUNT FROM SESSION_PRIVS
    WHERE PRIVILEGE IN ('CREATE TABLE','CREATE SEQUENCE','CREATE PROCEDURE');
  IF V_COUNT<>3 THEN
    RAISE_APPLICATION_ERROR(-20102,'CREATE TABLE, CREATE SEQUENCE, CREATE PROCEDURE privileges required.');
  END IF;
END;
/
-- Table-space quota, character set and actual Oracle version must also be checked before installation.
SELECT USER AS SCHEMA_NAME FROM DUAL;
SELECT PARAMETER,VALUE FROM NLS_DATABASE_PARAMETERS WHERE PARAMETER IN ('NLS_CHARACTERSET','NLS_NCHAR_CHARACTERSET');
SELECT PRIVILEGE FROM SESSION_PRIVS WHERE PRIVILEGE IN ('CREATE SESSION','CREATE TABLE','CREATE SEQUENCE','CREATE PROCEDURE');
