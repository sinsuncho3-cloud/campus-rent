-- Full development-fixture verification. Use install_dev.sql; SQL errors must stop the script.
-- Smoke tests roll back their rows; sequence increments are intentionally not rolled back by Oracle.
DECLARE
  V_COUNT NUMBER;
  V_ID NUMBER;
  V_ITEM1 NUMBER;
  V_ITEM2 NUMBER;
  V_FAILED BOOLEAN;
  PROCEDURE ASSERT_COUNT(P_EXPECT NUMBER,P_ACTUAL NUMBER,P_LABEL VARCHAR2) IS
  BEGIN
    IF P_EXPECT<>P_ACTUAL THEN RAISE_APPLICATION_ERROR(-20110,P_LABEL||': expected '||P_EXPECT||', got '||P_ACTUAL); END IF;
  END;
BEGIN
  SELECT COUNT(*) INTO V_COUNT FROM USER_TABLES;
  ASSERT_COUNT(26,V_COUNT,'Table count');
  SELECT COUNT(*) INTO V_COUNT FROM USER_TAB_COLUMNS;
  ASSERT_COUNT(185,V_COUNT,'ERD column count');
  SELECT COUNT(*) INTO V_COUNT FROM USER_SEQUENCES;
  ASSERT_COUNT(17,V_COUNT,'Sequence count');
  SELECT COUNT(*) INTO V_COUNT FROM USER_OBJECTS WHERE STATUS<>'VALID';
  ASSERT_COUNT(0,V_COUNT,'Invalid objects');
  SELECT COUNT(*) INTO V_COUNT FROM USER_CONSTRAINTS WHERE STATUS<>'ENABLED' OR VALIDATED<>'VALIDATED';
  ASSERT_COUNT(0,V_COUNT,'Disabled/unvalidated constraints');
  SELECT COUNT(*) INTO V_COUNT FROM APP_USER;
  ASSERT_COUNT(3,V_COUNT,'Initial accounts');
  SELECT COUNT(*) INTO V_COUNT FROM APP_USER WHERE
    (USER_ID=1 AND EMAIL='admin@campusrent.example' AND ROLE_CODE='ADMIN') OR
    (USER_ID=2 AND EMAIL='demo@campusrent.example' AND ROLE_CODE='STUDENT') OR
    (USER_ID=3 AND EMAIL='other@campusrent.example' AND ROLE_CODE='STUDENT');
  ASSERT_COUNT(3,V_COUNT,'Seed roles');
  SELECT COUNT(*) INTO V_COUNT FROM APP_USER WHERE REGEXP_LIKE(PASSWORD,'^\{pbkdf2@SpringSecurity_v5_8\}[0-9a-f]{96}$');
  ASSERT_COUNT(3,V_COUNT,'Encoded password format (Java tests verify the actual passwords)');
  SELECT COUNT(*) INTO V_COUNT FROM EQUIPMENT;
  ASSERT_COUNT(7,V_COUNT,'Equipment');
  SELECT COUNT(*) INTO V_COUNT FROM EQUIPMENT_COMPONENT;
  ASSERT_COUNT(24,V_COUNT,'Default components');
  SELECT COUNT(*) INTO V_COUNT FROM FACILITY;
  ASSERT_COUNT(5,V_COUNT,'Facilities');
  SELECT COUNT(*) INTO V_COUNT FROM FACILITY_HOURS;
  ASSERT_COUNT(35,V_COUNT,'Facility hours');
  SELECT COUNT(*) INTO V_COUNT FROM FACILITY_PURPOSE;
  ASSERT_COUNT(10,V_COUNT,'Permitted facility purposes');
  SELECT COUNT(*) INTO V_COUNT FROM USE_PURPOSE;
  ASSERT_COUNT(4,V_COUNT,'Purposes');

  SAVEPOINT VERIFY_FIXTURES;
  V_ID:=SQ_RENT_REQUEST.NEXTVAL;
  INSERT INTO RENT_REQUEST (REQUEST_ID,REQUEST_NO,APPLICANT_ID) VALUES (V_ID,'VERIFY-'||TO_CHAR(V_ID),2);
  V_ITEM1:=SQ_REQUEST_ITEM.NEXTVAL;
  V_ITEM2:=SQ_REQUEST_ITEM.NEXTVAL;
  INSERT INTO REQUEST_ITEM (REQUEST_ITEM_ID,REQUEST_ID,ITEM_NO,ITEM_KIND,EQUIPMENT_ID,USE_START_AT,USE_END_AT,ORIGIN_CODE)
    VALUES (V_ITEM1,V_ID,1,'E',2,CAST(TRUNC(CURRENT_DATE)+2 AS TIMESTAMP)+INTERVAL '10' HOUR,CAST(TRUNC(CURRENT_DATE)+2 AS TIMESTAMP)+INTERVAL '12' HOUR,'DIRECT');
  INSERT INTO REQUEST_ITEM (REQUEST_ITEM_ID,REQUEST_ID,ITEM_NO,ITEM_KIND,EQUIPMENT_ID,USE_START_AT,USE_END_AT,ORIGIN_CODE)
    VALUES (V_ITEM2,V_ID,2,'E',2,CAST(TRUNC(CURRENT_DATE)+2 AS TIMESTAMP)+INTERVAL '11' HOUR,CAST(TRUNC(CURRENT_DATE)+2 AS TIMESTAMP)+INTERVAL '13' HOUR,'DIRECT');

  V_FAILED:=FALSE;
  BEGIN APPROVE_REQUEST_ITEM(V_ITEM1,2,1);
  EXCEPTION WHEN OTHERS THEN IF SQLCODE=-20002 THEN V_FAILED:=TRUE; ELSE RAISE; END IF; END;
  IF NOT V_FAILED THEN RAISE_APPLICATION_ERROR(-20111,'Student was allowed to approve.'); END IF;

  APPROVE_REQUEST_ITEM(V_ITEM1,1,1);
  SELECT COUNT(*) INTO V_COUNT FROM REQUEST_ITEM WHERE REQUEST_ITEM_ID=V_ITEM1 AND STATUS_CODE='APPROVED' AND ROW_VERSION=2;
  ASSERT_COUNT(1,V_COUNT,'Approval transition');
  SELECT COUNT(*) INTO V_COUNT FROM REQUEST_STATUS_LOG WHERE REQUEST_ITEM_ID=V_ITEM1 AND TO_STATUS='APPROVED';
  ASSERT_COUNT(1,V_COUNT,'Approval audit');

  V_FAILED:=FALSE;
  BEGIN APPROVE_REQUEST_ITEM(V_ITEM2,1,1);
  EXCEPTION WHEN OTHERS THEN IF SQLCODE=-20015 THEN V_FAILED:=TRUE; ELSE RAISE; END IF; END;
  IF NOT V_FAILED THEN RAISE_APPLICATION_ERROR(-20112,'Conflicting approval was allowed.'); END IF;

  V_FAILED:=FALSE;
  BEGIN APPROVE_REQUEST_ITEM(V_ITEM1,1,1);
  EXCEPTION WHEN OTHERS THEN IF SQLCODE=-20004 THEN V_FAILED:=TRUE; ELSE RAISE; END IF; END;
  IF NOT V_FAILED THEN RAISE_APPLICATION_ERROR(-20113,'Stale approval was allowed.'); END IF;

  V_FAILED:=FALSE;
  BEGIN
    INSERT INTO REQUEST_ITEM (REQUEST_ITEM_ID,REQUEST_ID,ITEM_NO,ITEM_KIND,FACILITY_ID,USE_START_AT,USE_END_AT,ORIGIN_CODE)
      VALUES (SQ_REQUEST_ITEM.NEXTVAL,V_ID,3,'F',1,LOCALTIMESTAMP+INTERVAL '2' DAY,LOCALTIMESTAMP+INTERVAL '3' DAY,'DIRECT');
  EXCEPTION WHEN OTHERS THEN IF SQLCODE=-2290 THEN V_FAILED:=TRUE; ELSE RAISE; END IF; END;
  IF NOT V_FAILED THEN RAISE_APPLICATION_ERROR(-20114,'Facility without people/purpose was allowed.'); END IF;
  ROLLBACK TO VERIFY_FIXTURES;
  DBMS_OUTPUT.PUT_LINE('PASS: schema, fixture counts, account hash formats and approval smoke tests.');
EXCEPTION WHEN OTHERS THEN
  -- No commit here; install_dev.sql rolls back seed DML on failure. DDL is already committed.
  RAISE;
END;
/
SELECT USER AS SCHEMA_NAME,SESSIONTIMEZONE AS SESSION_TIME_ZONE FROM DUAL;
SELECT USER_ID,EMAIL,USER_NAME,ROLE_CODE FROM APP_USER ORDER BY USER_ID;
SELECT NAME,TYPE,LINE,POSITION,TEXT FROM USER_ERRORS ORDER BY NAME,SEQUENCE;
